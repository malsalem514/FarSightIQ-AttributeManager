import oracledb from 'oracledb';
import { withConnection, createPool } from '../src/services/oracle-pool.ts';
import dotenv from 'dotenv';
dotenv.config();

async function createHierarchyRuleTables() {
  try {
    console.log('--- Initializing Oracle Pool ---');
    await createPool();

    await withConnection(async (conn) => {
      console.log('--- Creating Attribute Hierarchy Rule Tables ---');

      await conn.execute(`
        BEGIN
          EXECUTE IMMEDIATE 'DROP TABLE ATTRIBUTE_HIERARCHY_RULES CASCADE CONSTRAINTS';
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
      `);
      
      await conn.execute(`
        CREATE TABLE ATTRIBUTE_HIERARCHY_RULES (
          RULE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          BUSINESS_UNIT_ID NUMBER NOT NULL,
          LEVEL_TYPE VARCHAR2(20) NOT NULL,
          LEVEL_ID VARCHAR2(50) NOT NULL,
          CHARACTERISTIC_TYPE_ID VARCHAR2(10) NOT NULL,
          IS_MANDATORY CHAR(1) DEFAULT 'N' CHECK (IS_MANDATORY IN ('Y', 'N')),
          APPLICABILITY VARCHAR2(20) DEFAULT 'OPTIONAL' CHECK (APPLICABILITY IN ('REQUIRED', 'OPTIONAL', 'NA')),
          DEFAULT_VALUE_ID VARCHAR2(10),
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          CREATED_BY VARCHAR2(50) DEFAULT 'SYSTEM',
          CONSTRAINT UNIQUE_LEVEL_CHAR UNIQUE (BUSINESS_UNIT_ID, LEVEL_TYPE, LEVEL_ID, CHARACTERISTIC_TYPE_ID)
        )
      `);
      console.log('✅ Created ATTRIBUTE_HIERARCHY_RULES');

      await conn.execute(`
        BEGIN
          EXECUTE IMMEDIATE 'DROP TABLE ATTRIBUTE_MAPPING_V2 CASCADE CONSTRAINTS';
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
      `);

      await conn.execute(`
        CREATE TABLE ATTRIBUTE_MAPPING_V2 (
          MAPPING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          BUSINESS_UNIT_ID NUMBER NOT NULL,
          LLM_TERM VARCHAR2(100) NOT NULL,
          CHARACTERISTIC_TYPE_ID VARCHAR2(10) NOT NULL,
          CHARACTERISTIC_VALUE_ID VARCHAR2(10) NOT NULL,
          CONFIDENCE_SCORE NUMBER(5,2),
          SEMANTIC_TAGS VARCHAR2(4000), 
          USAGE_COUNT NUMBER DEFAULT 0,
          LAST_USED TIMESTAMP,
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          CREATED_BY VARCHAR2(50) DEFAULT 'SYSTEM',
          CONSTRAINT UNIQUE_LLM_MAPPING UNIQUE (BUSINESS_UNIT_ID, LLM_TERM, CHARACTERISTIC_TYPE_ID)
        )
      `);
      console.log('✅ Created ATTRIBUTE_MAPPING_V2');

      const seedRules = [
        { buId: 1, lType: 'DEPT', lId: '10', cType: 'MAT', isMand: 'Y', appl: 'REQUIRED' },
        { buId: 1, lType: 'DEPT', lId: '10', cType: 'FIT', isMand: 'Y', appl: 'REQUIRED' },
        { buId: 1, lType: 'DEPT', lId: '10', cType: 'SLV', isMand: 'N', appl: 'OPTIONAL' },
        { buId: 1, lType: 'DEPT', lId: '10', cType: 'COL', isMand: 'N', appl: 'OPTIONAL' },
        { buId: 1, lType: 'DEPT', lId: '20', cType: 'MAT', isMand: 'Y', appl: 'REQUIRED' },
        { buId: 1, lType: 'DEPT', lId: '20', cType: 'FIT', isMand: 'Y', appl: 'REQUIRED' },
      ];

      for (const rule of seedRules) {
        await conn.execute(
          `INSERT INTO ATTRIBUTE_HIERARCHY_RULES 
           (BUSINESS_UNIT_ID, LEVEL_TYPE, LEVEL_ID, CHARACTERISTIC_TYPE_ID, IS_MANDATORY, APPLICABILITY) 
           VALUES (:buId, :lType, :lId, :cType, :isMand, :appl)`,
          rule
        );
      }
      
      await conn.commit();
      console.log('✅ Seeded hierarchy rules');
    });
  } catch (err) {
    console.error('❌ Error creating tables:', err);
  } finally {
    process.exit(0);
  }
}

createHierarchyRuleTables();

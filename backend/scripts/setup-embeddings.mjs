import oracledb from 'oracledb';
import { withConnection, createPool } from '../src/services/oracle-pool.js';
import dotenv from 'dotenv';
dotenv.config();

async function createEmbeddingTable() {
  try {
    await createPool();
    await withConnection(async (conn) => {
      console.log('--- Creating Attribute Embedding Cache ---');

      await conn.execute(`
        BEGIN
          EXECUTE IMMEDIATE 'DROP TABLE ATTRIBUTE_EMBEDDING_CACHE CASCADE CONSTRAINTS';
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
      `);
      
      await conn.execute(`
        CREATE TABLE ATTRIBUTE_EMBEDDING_CACHE (
          CACHE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          TERM VARCHAR2(500) NOT NULL,
          VECTOR_JSON CLOB NOT NULL, 
          PROVIDER VARCHAR2(50) DEFAULT 'OPENAI',
          MODEL VARCHAR2(50) DEFAULT 'text-embedding-3-small',
          CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          CONSTRAINT UNIQUE_TERM_MODEL UNIQUE (TERM, MODEL)
        )
      `);
      console.log('✅ Created ATTRIBUTE_EMBEDDING_CACHE');
      
      await conn.commit();
    });
  } catch (err) {
    console.error('❌ Error creating table:', err);
  } finally {
    process.exit(0);
  }
}

createEmbeddingTable();
